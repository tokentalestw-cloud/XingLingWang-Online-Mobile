const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(path.join(__dirname,'../static/battle_feedback.js'),'utf8');
const context=vm.createContext({setTimeout,clearTimeout,console});vm.runInContext(source,context);
const api=context.XLWBFeedback;let tests=0;
const score=(field,bonus,units={})=>({field,bonus,total:field+bonus,units});
assert.equal(api.scoreDifference(null,score(3,0)),null);tests++;
let d=api.scoreDifference(score(0,0),score(3,0,{a:{name:'盾牌人偶',stars:3,count:1}}));
assert.equal(d.delta,3);assert.equal(d.field,3);assert(d.reason.includes('盾牌人偶'));tests++;
d=api.scoreDifference(score(6,2,{a:{name:'甲',stars:6,count:2}}),score(3,1,{a:{name:'甲',stars:3,count:1}}));
assert.equal(d.delta,-4);assert.equal(d.field,-3);assert.equal(d.bonus,-1);assert(d.reason.includes('額外加分 -1★'));tests++;
assert.equal(api.scoreDifference(score(3,1),score(2,2)),null,'No false total-score popup when sources offset');tests++;
d=api.scoreDifference(score(-2,0),score(-4,0));assert.equal(d.delta,-2);tests++;
let base={multi:true,socket:1,ready:false,peerJoined:true,active:true,myTurn:true};
assert.equal(api.presence(base).kind,'syncing','Open socket is not yet a recovered game');tests++;
assert.equal(api.presence({...base,ready:true}).kind,'connected');tests++;
assert.equal(api.presence({...base,socket:3}).kind,'reconnecting');tests++;
assert.equal(api.presence({...base,failed:true}).kind,'paused');tests++;
assert.equal(api.presence({...base,ready:true,peerOffline:true}).label,'等待對手重連');tests++;
assert.equal(api.presence({...base,ready:true,peerJoined:false}).label,'等待對手加入');tests++;
assert.equal(api.presence({multi:false,active:true,myTurn:false}).label,'對手思考中');tests++;
assert.equal(api.presence({multi:false,active:true,over:true}).kind,'finished');tests++;
const blocked={myTurn:true,phase:'召喚階段',tribute:3,units:1};
assert(api.unavailableReason(blocked).includes('需要 3 個單位，目前只有 1 個'));tests++;
assert(api.unavailableReason({...blocked,needsDraw:true}).includes('先抽'));tests++;
assert(api.unavailableReason({...blocked,normalUsed:true}).includes('次數已使用'));tests++;
assert(api.unavailableReason({...blocked,magic:true,counterOnly:true}).includes('不能主動發動'));tests++;
assert(api.unavailableReason({...blocked,myTurn:false}).includes('對手回合'));tests++;
assert(api.unavailableReason({...blocked,magic:true,phase:'進攻宣言'}).includes('進攻宣言階段不能'));tests++;
assert.equal(api.goalProgress(17),3);assert.equal(api.goalProgress(19),1);tests++;
assert.equal(api.goalProgress(20),null,'Reaching the threshold does not imply automatic victory');tests++;
assert.equal(api.goalProgress(16),null);tests++;
assert.equal(JSON.stringify(api.strongestLanes({total:18,lanes:[1,4,2,4,0]})),'[1,3]');tests++;
assert.equal(api.strongestLanes({total:18,lanes:[0,0,0,0,0]}).length,0);tests++;
assert.equal(api.presence({...base,ready:true,phase:'起手換牌'}).label,'等待雙方換牌');tests++;
console.log(`${tests} action, score-source and connection presentation checks: PASS`);
